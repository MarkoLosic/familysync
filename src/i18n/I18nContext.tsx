interface I18nContextType {
  language: AppLanguage;
  setLanguage: (next: AppLanguage) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

const LANGUAGE_STORAGE_KEY = '@spona_language';

export const languageOptions: Array<{ code: AppLanguage; label: string }> = [
  { code: 'en', label: 'English' },
  { code: 'sr', label: 'Srpski' },
  { code: 'hr', label: 'Hrvatski' },
  { code: 'bs', label: 'Bosanski' },
  { code: 'de', label: 'Deutsch' },
];

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>('en');

  useEffect(() => {
    const loadLanguage = async () => {
      try {
        const saved = await AsyncStorage.getItem(LANGUAGE_STORAGE_KEY);
        if (saved === 'en' || saved === 'sr' || saved === 'hr' || saved === 'bs' || saved === 'de') {
          setLanguageState(saved);
        }
      } catch (error) {
        console.log('Error loading language:', error);
      }
    };

    loadLanguage();
  }, []);

  const setLanguage = async (next: AppLanguage) => {
    setLanguageState(next);
    try {
      await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch (error) {
      console.log('Error saving language:', error);
    }
  };

  const value = useMemo<I18nContextType>(
    () => ({
      language,
      setLanguage,
      t: (key) => translations[language][key] ?? en[key] ?? key,
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return context;
}
